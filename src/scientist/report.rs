//! `machine report`: a markdown research note from beliefs, ranking and
//! learnings. Every claim in it is a belief with an interval or a recorded
//! learning; the report adds structure, not new numbers.

use super::analyze::Analysis;
use super::beliefs::Status;
use super::selector::{Candidate, MIN_SCORE};
use crate::learnings::Learning;
use std::fmt::Write;

pub fn markdown(a: &Analysis, ranked: &[Candidate], learned: &[Learning], flags: &str) -> String {
    let b = &a.beliefs;
    let mut s = String::new();
    let w = &mut s;
    let _ = writeln!(w, "# Research note: local inference on `{}`\n", b.backend);
    let _ = writeln!(
        w,
        "_Generated by `machine report` at {} from {} run rows, {} agent episodes and {} autopilot learnings.{}_\n",
        b.fitted_at,
        b.run_rows,
        b.agent_episodes,
        learned.len(),
        if b.simulated {
            " **All data is SIMULATED (mock backend): this describes the simulator, not hardware.**"
        } else {
            ""
        }
    );

    // Summary: the strongest statements, in plain words.
    let _ = writeln!(w, "## Summary\n");
    let g = |k: &str| b.get(k);
    let mut bullets: Vec<String> = Vec::new();
    if let (Some(f), Some(p), Some(d)) = (
        g("prefill.fixed_ms"),
        g("prefill.ms_per_token"),
        g("decode.ms_per_token"),
    ) && let (Some(fe), Some(pe), Some(de)) = (f.est, p.est, d.est)
    {
        bullets.push(format!(
            "A call costs about **{:.0} ms fixed + {:.2} ms per evaluated prompt token** to prefill and **{:.1} ms per generated token** to decode.",
            fe.value, pe.value, de.value
        ));
    }
    if let Some(share) = a.surrogate.agent_prefill_share() {
        bullets.push(format!(
            "For the baseline agent, prefill is **{:.0}%** of each call, so prompt-side changes (caching, shorter prompts) are the main lever on agent speed.",
            share * 100.0
        ));
    }
    for x in b
        .beliefs
        .iter()
        .filter(|x| x.effect && x.status == Status::Known && x.key.starts_with("effect."))
    {
        bullets.push(format!("{}: **{}**.", capitalise(&x.what), x.fmt_est()));
    }
    for x in b.beliefs.iter().filter(|x| x.status == Status::Negligible) {
        bullets.push(format!(
            "No practical effect: {} ({}).",
            x.what,
            x.fmt_est()
        ));
    }
    for an in &b.anomalies {
        if !an.key.starts_with("prediction_miss") {
            bullets.push(format!("Anomaly — {}.", an.title.to_lowercase()));
        }
    }
    if bullets.is_empty() {
        bullets
            .push("Not enough data for conclusions yet; see the recommended experiments.".into());
    }
    for x in bullets {
        let _ = writeln!(w, "- {x}");
    }

    // Cost model table.
    let _ = writeln!(w, "\n## Cost model\n");
    let _ = writeln!(
        w,
        "| belief | estimate [95% interval] | n | status | method |"
    );
    let _ = writeln!(w, "|---|---|---|---|---|");
    for x in b.beliefs.iter().filter(|x| {
        x.key.starts_with("prefill.")
            || x.key.starts_with("decode.")
            || x.key.starts_with("overhead")
            || x.key.starts_with("noise")
    }) {
        let _ = writeln!(
            w,
            "| `{}` — {} | {} | {} | {} | {} |",
            x.key,
            x.what,
            x.fmt_est(),
            x.n,
            x.status.tag().trim().to_lowercase(),
            x.method
        );
    }

    for (title, st) in [
        ("What we now know", Status::Known),
        ("Known to be practically zero", Status::Negligible),
        ("What is still uncertain", Status::Uncertain),
        ("Untested", Status::Untested),
    ] {
        let xs: Vec<_> = b
            .beliefs
            .iter()
            .filter(|x| {
                x.status == st
                    && (x.key.starts_with("effect.")
                        || x.key.starts_with("interaction")
                        || x.key.starts_with("agent."))
            })
            .collect();
        let _ = writeln!(w, "\n## {title}\n");
        if xs.is_empty() {
            let _ = writeln!(w, "_Nothing in this category._");
        }
        for x in xs {
            let _ = writeln!(w, "- `{}` — {}: {} (n={})", x.key, x.what, x.fmt_est(), x.n);
        }
    }

    if !b.agent_configs.is_empty() {
        let _ = writeln!(w, "\n## Agent configurations (10-task runs)\n");
        let _ = writeln!(
            w,
            "| config | episodes | success [95%] | calls/task | wall/task | prompt tok/call | format errors/task |"
        );
        let _ = writeln!(w, "|---|---|---|---|---|---|---|");
        for c in &b.agent_configs {
            let _ = writeln!(
                w,
                "| `{}` | {} | {:.0}% [{:.0}, {:.0}] | {:.1} | {:.0} ms | {:.0} | {:.2} |",
                c.key,
                c.episodes,
                c.success.value * 100.0,
                c.success.lo * 100.0,
                c.success.hi * 100.0,
                c.calls.value,
                c.wall_ms.value,
                c.prompt_per_call,
                c.format_errors_per_task
            );
        }
    }
    if !b.failure_modes.is_empty() {
        let _ = writeln!(w, "\n### Failure modes\n");
        for f in &b.failure_modes {
            let _ = writeln!(
                w,
                "- **{}** — {} episodes ({:.0}% of failures). Rule: {}.",
                f.mode,
                f.episodes,
                f.share * 100.0,
                f.rule
            );
        }
        for s in &b.systematic_failures {
            let _ = writeln!(
                w,
                "- Systematic: {s}. No knob fixes this; it is a model-capability limit on this task."
            );
        }
    }

    let _ = writeln!(w, "\n## Broken assumptions and anomalies\n");
    if b.anomalies.is_empty() {
        let _ = writeln!(w, "_None detected._");
    }
    for an in &b.anomalies {
        let _ = writeln!(
            w,
            "- **{}**  \n  Evidence: {}  \n  Consequence: {}",
            an.title, an.evidence, an.consequence
        );
    }

    let _ = writeln!(w, "\n## Recommended next experiments\n");
    let _ = writeln!(
        w,
        "Ranked by `score = gain × (0.25 + 0.75·value) / (1 + log2(1 + cost_s/10))`. Each is a single-variable command with its predictions.\n"
    );
    let worth: Vec<&Candidate> = ranked
        .iter()
        .filter(|c| c.score >= MIN_SCORE)
        .take(5)
        .collect();
    if worth.is_empty() {
        let _ = writeln!(
            w,
            "_Nothing left above the value threshold; change the environment (new task, new tool, new model) to learn more._"
        );
    }
    for (i, c) in worth.iter().enumerate() {
        let _ = writeln!(
            w,
            "{}. **{}** — score {:.3} (gain {:.2}, value {:.2}, ~{}). {}  \n   `{}`",
            i + 1,
            c.proposal.key,
            c.score,
            c.gain,
            c.value,
            crate::autopilot::fmt_ms(c.cost_ms),
            c.why,
            c.proposal.command(flags)
        );
    }

    if !learned.is_empty() {
        let _ = writeln!(w, "\n## Learnings so far\n");
        for l in learned {
            let _ = writeln!(
                w,
                "- {} **{}** {} — {}",
                l.ts,
                l.key,
                if l.passed { "✓" } else { "✗" },
                l.learning
            );
        }
    }

    let _ = writeln!(w, "\n## Methods and limitations\n");
    for m in &b.methods {
        let _ = writeln!(w, "- {m}");
    }
    let _ = writeln!(
        w,
        "- Agent effects are measured on 10 arithmetic tasks with one small model; intervals are wide and the conclusions are about this setup only.\n- The surrogate is two straight lines plus a constant. It extrapolates poorly beyond the measured prompt/output lengths and knows nothing about batching, GPU offload or other load-time settings."
    );
    s
}

fn capitalise(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}
